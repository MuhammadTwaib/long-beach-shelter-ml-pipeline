import argparse
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

import pandas as pd

from src import analysis, cleaning, config, validation


def rel(path):
    """Show a path relative to the project folder (clean logs on any machine)."""
    path = Path(path).resolve()
    return str(path.relative_to(config.ROOT)) if path.is_relative_to(config.ROOT) else str(path)


def missing_pct(df):
    """Percent of missing values per column, rounded to 2 decimals."""
    return (100 * df.isna().mean()).round(2)


def typed_raw(raw):
    """Raw data with only renaming + type parsing (no cleaning) - the 'before' state."""
    df = cleaning.blank_to_nan(cleaning.rename_columns(raw))
    df, _ = cleaning.fix_types(df)
    return df


def build_metrics(raw_typed, clean, log, report_before, report_after, input_path, status):
    """Collect every data-quality number in one JSON-friendly dict."""
    before, after = missing_pct(raw_typed), missing_pct(clean)
    shared = before.index.intersection(after.index)
    return {
        "run_at_utc": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "input_file": rel(input_path),
        "status": status,
        "threshold": config.VALIDATION_PASS_THRESHOLD,
        "rows_raw": log["rows_raw"],
        "rows_clean": log["rows_clean"],
        "duplicates_removed": log["duplicates_removed"],
        "rows_rejected_pct": round(100 * log["duplicates_removed"] / log["rows_raw"], 3),
        "values_fixed": {k: v for k, v in log.items() if k.endswith("_blanked")},
        "parse_failures": log["parse_failures"],
        "rows_without_usable_label": int(clean["bad_outcome"].isna().sum()),
        "overall_missing_pct_before": round(float(before[shared].mean()), 3),
        "overall_missing_pct_after": round(float(after[shared].mean()), 3),
        "validation_before": {
            "row_pass_rate": round(report_before["row_pass_rate"], 4),
            "checks_passed": report_before["checks_passed"],
            "checks_total": report_before["checks_total"],
        },
        "validation_after": {
            "row_pass_rate": round(report_after["row_pass_rate"], 4),
            "checks_passed": report_after["checks_passed"],
            "checks_total": report_after["checks_total"],
            "critical_failures": report_after["critical_failures"],
        },
    }


def write_quality_report(metrics, before_checks, after_checks, before_missing, after_missing, path):
    """Write a human-readable Markdown data-quality report with before/after tables."""
    miss = pd.DataFrame({"missing_%_raw": before_missing, "missing_%_clean": after_missing})
    miss = miss[(miss.fillna(0) > 0).any(axis=1)]
    checks = before_checks.merge(after_checks, on="check", suffixes=("_raw", "_clean"))
    checks = checks[["check", "rows_failed_raw", "rows_failed_clean"]]
    va, vb = metrics["validation_after"], metrics["validation_before"]
    lines = [
        "# Data-quality report",
        "",
        f"Generated by `python -m src.pipeline_a` at {metrics['run_at_utc']} (UTC).",
        "",
        "## Headline metrics",
        "",
        "| Metric | Before (raw) | After (clean) |",
        "|---|---|---|",
        f"| Rows | {metrics['rows_raw']:,} | {metrics['rows_clean']:,} |",
        f"| Validation row pass rate | {vb['row_pass_rate']:.2%} | {va['row_pass_rate']:.2%} |",
        f"| Checks fully passed | {vb['checks_passed']}/{vb['checks_total']} | {va['checks_passed']}/{va['checks_total']} |",
        f"| Mean % missing (all columns) | {metrics['overall_missing_pct_before']} | {metrics['overall_missing_pct_after']} |",
        "",
        f"* Duplicate rows removed: **{metrics['duplicates_removed']}** "
        f"({metrics['rows_rejected_pct']}% of raw rows) - saved to `data/cleaned/shelter_rejected.csv`.",
        f"* Impossible values blanked: {metrics['values_fixed']}.",
        f"* Rows kept but without a usable ML label (no / missing outcome): {metrics['rows_without_usable_label']}.",
        f"* Quality gate threshold: {metrics['threshold']:.0%} row pass rate -> status **{metrics['status']}**.",
        "",
        "## Validation checks (rows failing)",
        "",
        checks.to_markdown(index=False),
        "",
        "## Missing values per column (%)",
        "",
        miss.to_markdown(),
        "",
        "Missing values that remain are *real* gaps (e.g. most animals have no",
        "`reason_for_intake` because they were strays). They are documented, not",
        "invented - see `docs/assumptions.md`.",
        "",
    ]
    path.write_text("\n".join(lines), encoding="utf-8")


def main(argv=None):
    """Run the whole Part A pipeline; returns 0 on success, 1 if the gate fails."""
    parser = argparse.ArgumentParser(description="Part A: data quality & insights pipeline")
    parser.add_argument("--input", type=Path, default=config.RAW_FILE, help="raw CSV to process")
    parser.add_argument("--metrics-out", type=Path, default=config.METRICS_FILE,
                        help="where to write metrics.json")
    args = parser.parse_args(argv)

    print(f"[1/6] Loading {rel(args.input)}")
    raw = cleaning.load_raw(args.input)

    print("[2/6] Measuring the raw data (before cleaning)")
    raw_typed = typed_raw(raw)
    report_before = validation.validate(raw_typed)

    print("[3/6] Cleaning")
    clean, rejected, log = cleaning.clean_all(raw)

    print("[4/6] Validating cleaned data + quality gate")
    report_after = validation.validate(clean)
    args.metrics_out.parent.mkdir(parents=True, exist_ok=True)
    try:
        validation.quality_gate(report_after)
        status = "passed"
    except validation.DataQualityError as err:
        metrics = build_metrics(raw_typed, clean, log, report_before, report_after, args.input, "failed")
        args.metrics_out.write_text(json.dumps(metrics, indent=2), encoding="utf-8")
        print(f"\n{err}\nMetrics written to {rel(args.metrics_out)}. Nothing else was saved.", file=sys.stderr)
        return 1

    metrics = build_metrics(raw_typed, clean, log, report_before, report_after, args.input, status)
    args.metrics_out.write_text(json.dumps(metrics, indent=2), encoding="utf-8")
    print(f"      gate passed: row pass rate {report_after['row_pass_rate']:.2%}")

    print("[5/6] Saving cleaned data (raw file is untouched)")
    config.CLEAN_DIR.mkdir(parents=True, exist_ok=True)
    clean.to_csv(config.CLEAN_FILE, index=False)
    rejected.to_csv(config.REJECTED_FILE, index=False)
    config.REPORT_DIR.mkdir(parents=True, exist_ok=True)
    report_before["checks"].to_csv(config.REPORT_DIR / "validation_raw.csv", index=False)
    report_after["checks"].to_csv(config.REPORT_DIR / "validation_clean.csv", index=False)
    write_quality_report(metrics, report_before["checks"], report_after["checks"],
                         missing_pct(raw_typed), missing_pct(clean),
                         config.REPORT_DIR / "data_quality_report.md")

    print("[6/6] Summaries, figures and SQL")
    files = analysis.run_analysis(clean, missing_pct(raw_typed), missing_pct(clean))
    print(f"Done. Wrote {len(files) + 6} files under data/cleaned and outputs/.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
